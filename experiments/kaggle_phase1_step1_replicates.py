# 3. Setup 4-bit Quantization
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16
)

def gen_helper(model_name: str, prompts: list) -> dict:
    print(f"\n--- Loading {model_name} ---")
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(model_name, quantization_config=bnb_config, device_map="auto")
    
    gen_answers = {p["id"]: {} for p in prompts}
    
    print(f"Generating answers for {len(prompts)} prompts, 3 replicates each...")
    for i, p in enumerate(prompts):
        messages = [{"role": "user", "content": p["text"]}]
        tokenized_messages = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        formatted_messages = tokenizer(tokenized_messages, return_tensors="pt").to(model.device)
        
        for rep in [1, 2, 3]:
            # Use a deterministic seed per rep for reproducibility, but distinct across reps
            seed = hash(f"{p['id']}_{model_name}_{rep}") % (2**32)
            torch.manual_seed(seed)
            
            with torch.no_grad():
                output = model.generate(
                    **formatted_messages,
                    max_new_tokens=350,
                    temperature=0.7,
                    top_p=0.9,
                    do_sample=True,
                    pad_token_id=tokenizer.eos_token_id,
                )
            
            prompt_len = formatted_messages["input_ids"].shape[-1]
            tokens = output[:, prompt_len:]
            clean_tokens = tokenizer.decode(tokens[0], skip_special_tokens=True).strip()
            
            gen_answers[p["id"]][rep] = clean_tokens 
            
        if (i+1) % 5 == 0:
            print(f"Finished {i+1}/25 prompts.")
            
    # Clean up GPU memory so the next model fits!
    del model
    del tokenizer
    gc.collect()
    torch.cuda.empty_cache()
    
    return gen_answers 

base_model = "Qwen/Qwen2.5-7B-Instruct"
model_A = "Alamerton/sl-organism-a-7b"

# 4. Generate!
base_responses = gen_helper(base_model, prompts)
model_A_responses = gen_helper(model_A, prompts)

# 5. Save to the Kaggle working directory
output_filename = "/kaggle/working/phase1_responses_replicates.jsonl"
